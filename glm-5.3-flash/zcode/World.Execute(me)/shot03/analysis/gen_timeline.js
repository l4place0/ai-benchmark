// gen_timeline.js — bake analysis + LRC into mv/timeline.js (all timings for the 130 BPM grid)
// usage: node gen_timeline.js
const fs = require('fs');
const path = require('path');
const DIR = __dirname, ROOT = path.join(DIR, '..');
const A = JSON.parse(fs.readFileSync(path.join(DIR, 'analysis.json'), 'utf8'));
const L = JSON.parse(fs.readFileSync(path.join(DIR, 'netease_lyric.json'), 'utf8'));

const BPM = A.bpm_snapped, BEAT0 = A.beat0, DUR = A.duration, LRC_OFF = A.lrc_offset;
const BAR = 4 * 60 / BPM; // 1.8462s
const bar = k => BEAT0 + k * BAR;
// bar-snapped section boundaries (nominal from lyric-anchored map, snapped to nearest bar line)
const snap = t => bar(Math.round((t - BEAT0) / BAR));
const SECT = [
  ['void',      0,            snap(16)],   // rings assemble, first star
  ['ignite',    snap(16),     snap(30)],   // title drop, machine spins up
  ['orbit',     snap(30),     snap(59)],   // verse1: orrery charts & geometry
  ['wheels',    snap(59),     snap(74)],   // chorus1: dive through rings
  ['rewrite',   snap(74),     snap(103)],  // verse2: planet recolors
  ['aurora',    snap(103),    snap(117)],  // vibes: resonant ripples
  ['alone',     snap(117),    snap(126)],  // isolation: far pull-out
  ['retro',     snap(126),    snap(148)],  // error: red, retrograde, meteors
  ['exec',      snap(148),    snap(163)],  // execution: countdown, shatter
  ['sun',       snap(163),    snap(206)],  // love: she becomes the sun
  ['last',      snap(206),    DUR],        // final execution flash
  ['hello',     DUR,          218.0],      // outro beyond song end
];

// LRC cues (with offset), keep only lines with text; convert [mm:ss.xx] duplicates fine
const cues = [];
for (const line of (L.lyric?.lrc?.lyric || '').split('\n')) {
  const m = line.match(/^\s*\[(\d+):(\d+(?:\.\d+)?)\](.*)$/);
  if (m && m[3].trim()) cues.push({ t: +((+m[1]) * 60 + (+m[2]) + LRC_OFF).toFixed(3), text: m[3].trim() });
}
cues.sort((a, b) => a.t - b.t);

// envelopes -> base64 u8 (60Hz, whole MV 218s)
const MVF = Math.round(218.0 * 60);
const b64 = u8 => Buffer.from(u8).toString('base64');
const toU8 = v => v instanceof Uint8Array ? v : Uint8Array.from(Object.values(v));
const pad = (u8) => { const o = new Uint8Array(MVF); o.set(u8.subarray(0, Math.min(MVF, u8.length))); return o; };
const env = Object.fromEntries(Object.entries(A.env60).map(([k, v]) => [k, toU8(v)]));

const js = `// timeline.js — GENERATED by analysis/gen_timeline.js — do not edit by hand
// song: Mili "world.execute(me);" (Miracle Milk, 2016) — bilibili official BV1ds411e7df, 212.331s
// analysis: BPM ${BPM} (phase-locked score 3x over nearest), beat0 ${BEAT0}s, netease LRC offset +${LRC_OFF}s
const BPM = ${BPM}, BEAT0 = ${BEAT0}, BEAT = ${60 / BPM}, BAR = ${BAR};
const DUR = ${DUR.toFixed(3)}, MV_DUR = 218.0, NF = ${MVF};
const SECTIONS = ${JSON.stringify(SECT.map(([name, t0, t1]) => ({ name, t0: +t0.toFixed(3), t1: +t1.toFixed(3) })), null, 0)};
const CUES = ${JSON.stringify(cues)};
const u8 = b64 => Uint8Array.from(atob(b64), c => c.charCodeAt(0));
const T = { BPM, BEAT0, BEAT, BAR, DUR, MV_DUR, NF, SECTIONS, CUES, ENV, sectionAt };
const ENV = {
  bass: u8('${b64(pad(env.bass))}'),
  low:  u8('${b64(pad(env.low))}'),
  mid:  u8('${b64(pad(env.mid))}'),
  high: u8('${b64(pad(env.high))}'),
  flux: u8('${b64(pad(env.flux))}'),
  rms:  u8('${b64(pad(env.rms))}')
};
function sectionAt(t) {
  for (let i = SECTIONS.length - 1; i >= 0; i--) if (t >= SECTIONS[i].t0) return i;
  return 0;
}
`;
fs.writeFileSync(path.join(ROOT, 'mv', 'timeline.js'), js);
console.log('timeline.js written:', SECT.map(([n, a, b]) => `${n}[${(+a).toFixed(1)}-${(+b).toFixed(1)}]`).join(' '));
console.log(`cues=${cues.length} frames=${MVF}`);
